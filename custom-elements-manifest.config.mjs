// =============================================================================
// Custom Elements Manifest — analyzer configuration
// =============================================================================
// Generates `custom-elements.json` at the package root. The manifest is the
// machine-readable API surface of every `<m-*>` component: tag names,
// reflected attributes, types, defaults, slots, and events.
//
// Why it exists: IDE tooling reads it via `package.json#customElements`, and
// it is the input for future auto-generation of the React / Vue / Angular
// wrappers (steps 5-7 of docs/INTEGRATION.md).
//
// The manifest is a BUILD ARTIFACT — generated by `npm run analyze`, which
// `npm run build` runs first. It is deliberately not committed; see .gitignore.
//
// Why `litelement: true` is mandatory: without it the analyzer emits no
// `tagName`, no `customElement: true`, and no `attributes[]` / `reflects`
// metadata for `@property` decorators.
//
// Why `packagejson: false`: the analyzer otherwise rewrites package.json
// (adding a `customElements` field) as a side effect of the run. The field is
// declared by hand in package.json instead.
//
// Why the `exclude` list: the analyzer auto-ignores `*.test.ts` and `*.d.ts`
// but NOT `*.stories.ts`, and a Storybook file would pollute the manifest
// with a second declaration of the same custom element.
// =============================================================================

export default {
  globs: ['src/components/**/m-*.ts'],
  exclude: ['**/*.test.ts', '**/*.stories.ts'],
  outdir: '.',
  litelement: true,
  packagejson: false,
};
